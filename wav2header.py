#!/usr/bin/env python3
"""
wav2header.py — turn a folder of .wav files into samples.h for the ESP32 sketch.

Usage:
    python wav2header.py my_sounds_folder
    python wav2header.py my_sounds_folder --out SpinSamples/samples.h --max-seconds 2.5

Each file becomes an array named after the file:
    kick.wav  ->  kick_data[], kick_len

The sketch expects: kick, snare, hat, crash, bass, pad, riser
Any WAV works (mono or stereo, 8/16/24/32-bit PCM, any sample rate). Files are
converted to mono, resampled to 22050 Hz, normalized, trimmed and stored as 8-bit.
Only uses the Python standard library.
"""

import argparse
import os
import re
import struct
import wave

RATE = 22050
EXPECTED = ["kick", "snare", "hat", "crash", "bass", "pad", "riser"]


def read_wav(path):
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)

    count = len(raw) // width
    if width == 1:
        vals = [(b - 128) / 128.0 for b in raw]
    elif width == 2:
        vals = [v / 32768.0 for v in struct.unpack("<%dh" % count, raw)]
    elif width == 3:
        vals = []
        for i in range(0, len(raw), 3):
            v = int.from_bytes(raw[i:i + 3], "little", signed=True)
            vals.append(v / 8388608.0)
    elif width == 4:
        vals = [v / 2147483648.0 for v in struct.unpack("<%di" % count, raw)]
    else:
        raise ValueError("unsupported sample width")

    mono = [sum(vals[i:i + ch]) / ch for i in range(0, len(vals), ch)]
    return mono, rate


def resample(x, src, dst):
    if src == dst or not x:
        return x
    n_out = int(len(x) * dst / src)
    out = []
    for i in range(n_out):
        p = i * src / dst
        j = int(p)
        f = p - j
        a = x[j]
        b = x[j + 1] if j + 1 < len(x) else a
        out.append(a + (b - a) * f)
    return out


def process(x, max_seconds, is_loop):
    peak = max((abs(v) for v in x), default=0)
    if peak > 0:
        x = [v / peak for v in x]
    if not is_loop:                                   # trim silence at the end
        end = len(x)
        while end > 0 and abs(x[end - 1]) < 0.01:
            end -= 1
        x = x[:end]
    max_len = int(max_seconds * RATE)
    if len(x) > max_len:
        x = x[:max_len]
        fade = min(int(0.01 * RATE), len(x))          # 10 ms fade-out to avoid a click
        for i in range(fade):
            x[len(x) - fade + i] *= 1 - i / fade
    return [max(-128, min(127, round(v * 127))) for v in x]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--out", default="samples.h")
    ap.add_argument("--max-seconds", type=float, default=2.5)
    args = ap.parse_args()

    files = sorted(f for f in os.listdir(args.folder) if f.lower().endswith(".wav"))
    lines = ["// Generated by wav2header.py — 8-bit signed, mono, %d Hz" % RATE,
             "#pragma once", "#include <stdint.h>", ""]
    found, total = [], 0

    for f in files:
        name = re.sub(r"\W", "_", os.path.splitext(f)[0].lower())
        x, rate = read_wav(os.path.join(args.folder, f))
        data = process(resample(x, rate, RATE), args.max_seconds, name == "pad")
        found.append(name)
        total += len(data)
        lines.append("const uint32_t %s_len = %d;" % (name, len(data)))
        lines.append("const int8_t %s_data[] = {" % name)
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        lines.append("};\n")
        print("%-10s %6d samples  (%.2f s)" % (name, len(data), len(data) / RATE))

    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))

    missing = [e for e in EXPECTED if e not in found]
    print("\nWrote %s  (%d KB of audio)" % (args.out, total // 1024))
    if missing:
        print("WARNING: missing sounds the sketch needs: " + ", ".join(missing))


if __name__ == "__main__":
    main()
